## 10. Agent 进程

这一页管着新对话从哪个文件夹开始、模型被告知了什
么，以及承载这两件事的进程。

### 模型拿到了什么

| 部分 | 内容 |
| --- | --- |
| 系统提示词 | pi 的角色、工具与调用规则，以及它的文档索引 |
| 指令文件 | PiKit 写的默认提示词，然后是你的，再是项目自己的 |
| 运行信息 | 模型、思考等级、会话文件、工作区和权限等级 |
| 工具 | read、bash、edit、write、grep、find、ls，以及扩展的搜索工具 |
| 对话 | 到目前为止的每条消息和每次工具结果 |

### 指令

- **默认提示词** 是 PiKit 的，只读：里面写了前
  缀目录、三档权限和工作区规则，每个新版本都会重
  写它。
- **用户指令** 只属于你，一开始是空的，PiKit
  永远不会改写；保存后 Agent 会重启，因为 pi 只
  在启动时读这个文件。
- **项目自己放在目录里的 `AGENTS.md`** 也会被
  读到，越靠近项目的那份越具体。

### 进程与保活

- **重启 Agent** 一键停止再启动；启动失败时，
  pi 自己的报错就显示在这一行下面。
- **后台保活** 是 Android 的电池优化豁免；这一
  行的副标题写着当前状态，只在还没拿到豁免时才问。
- **通知栏条目** 只在有回答正在写、并且应用在
  后台时出现，它写明有几个对话正在回答。

## 11. 备份与恢复

卸载 PiKit 会删掉全部配置和其中的 Key、所有对话
以及工作区，而本应用不往云端备份；**设置 → 备份
与恢复**是保住它们的唯一办法。

### 备份包里有什么

| 类别 | 内容 |
| --- | --- |
| 基础设置 | 主题、语言、默认工作区、权限等级和每一项偏好 |
| 模型与供应商配置 | 每个保存的配置及其 Key，以及 pi 读它们的文件 |
| 全部历史对话 | 每个对话一个文件，以及哪些被置顶 |

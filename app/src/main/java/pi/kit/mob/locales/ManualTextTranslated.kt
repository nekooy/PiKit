| インライン内容の上限（文字） | 1 ページの何文字をモデルに渡すか |
| 取得タイムアウト（秒） | 1 ページの取得に待つ秒数 |
| プロキシ | 拡張のリクエストが通るプロキシ |

### 設定ファイル

- **設定項目** は、上のスイッチが書かない
  `web-search.json` のキーの一覧です。
- **設定項目またはキーを追加** は 1 つ選び、そ
  の項目が期待する形で値を保存します。✕ はその項
  目だけを消します。
- **各サービスの API キーや自前 SearXNG のアド
  レス** もそこで追加します。
- **既定に戻す** はファイルをインストール直後
  の内容に戻します。
- **JSON オブジェクトでなくなったファイル** で
  はスイッチがテキストエディターに変わり、正しい
  JSON を保存するとまた編集できるようになります。

> **警告：** **既定に戻す** は追加したキーと
> 設定項目をすべて消します。ページが先に確認
> します。


## 10. エージェントのプロセス

このページは、新しい会話が始まるフォルダー、モデ
ルに伝える内容、そしてその両方を運ぶプロセスを持
ちます。

### モデルに渡るもの

| 部分 | 内容 |
| --- | --- |
| システムプロンプト | pi の役割、ツールと呼び出しの規則、ドキュメントの索引 |
| 指示ファイル | PiKit が書く既定の指示、次にあなたの指示、次にプロジェクト自身のもの |
| 実行時の情報 | モデル、思考レベル、セッションファイル、ワークスペース、権限の段階 |
| ツール | read、bash、edit、write、grep、find、ls、および拡張の検索ツール |
| 会話 | これまでのすべてのメッセージとツールの結果 |

### 指示

- **既定の指示** は PiKit のもので読み取り専用
  です。プレフィックス、3 つの段階、ワークスペー
  スのルールが書かれ、ビルドごとに書き直されます。
- **ユーザーの指示** はあなただけのもので、最
  初は空、PiKit は決して書き換えません。保存する
  とエージェントが再起動します。pi は起動時にし
  かこのファイルを読まないためです。
- **プロジェクトが自分のフォルダーに置いた
  `AGENTS.md`** も読まれ、プロジェクトに近いほう
  が優先されます。

### プロセスとバックグラウンド保護

- **エージェントを再起動** は停止と起動を 1 タ
  ップで行います。起動に失敗すると、pi 自身のエ
  ラーがこの行の下に出ます。
- **バックグラウンド保護** は Android のバッテ
  リー最適化の除外です。行の説明が現在の状態を示
  し、除外がないときだけ尋ねます。
- **通知領域の項目** は、回答を書いている最中
  でアプリがバックグラウンドにあるときだけ出て、
  何件の会話が応答中かを示します。

## 11. バックアップと復元

PiKit をアンインストールすると、プロファイルとそ
のキー、全会話、ワークスペースが消えます。クラウ
ドへの控えは取りません。**設定 → バックアップと
復元**が唯一の備えです。

### バックアップの中身

| 種類 | 内容 |
| --- | --- |
| 基本設定 | テーマ、言語、既定のワークスペース、権限の段階、すべての設定 |
| モデルとプロバイダー | 保存したプロファイルとキー、pi が読むファイル |
| 会話履歴の全部 | 会話ごとに 1 ファイル、どれがピン留めか |
| エージェントのプロンプト | 既定の指示とユーザーの指示の 2 文書 |
| ワークスペースのファイル | エージェントのホームのワークスペース全部と、追加したフォルダー |
| HTML エクスポート | `/export` が `~/export` に書いたファイル |

### 書き出しと復元

- **最初からチェックが入る** のは最初の 3 種類
  です。**ワークスペースのファイル**が外れている
  のは、ワークスペースがプロジェクト一式になりう
  るからです。
- **API キーを含める** は既定でオンです。オフ
  にするとアーカイブにキーは 1 つも入りません。
- **バックアップを選ぶ…** は、どの種類か、いつ
  ものか、どのバージョンか、キーが入っているかを
  先に見せてから動きます。
- **復元** はエージェントを止め、同名のファイ
  ルを上書きするだけで、何も削除しません。終わる
  とエージェントが復元後の設定で起動します。
- **実行環境はアーカイブに入りません**：`usr`
  は APK から展開し直します。

> **ヒント：** アーカイブはキーの唯一の控え
> です。端末の外にも 1 つ残してください。

## 12. 問題が起きたとき

ほとんどの失敗は原因を名乗ります。ここにあるのは、
出口のあるものです。

### 回答

- **`Stream ended without finish_reason`**：エ
  ンドポイントかネットワークが最後のチャンクの前
  にストリームを閉じました。エージェントは自分で
  最大 8 回やり直します。何度も出るなら回線を変
  えるか、その提供元が `finish_reason` を送るか
  確認してください。
- **モデルが「not found」「unauthorised」を返
  す**：そのキーではそのモデルを使えません。一覧
  を取り直すか、提供元が返す ID を入れてください。
  中継ならベース URL のバージョンセグメントも確
  認します。
- **ツール呼び出しが拒否された**：権限の段階が
  断りました。✕ の付いた行に段階名とパスが出るの
  で、入力欄の下のボタンで段階を変えるか、ワーク
  スペースを変えてください。

### プロセス

- **`pi exited with code 1`**：プロセスが起動
  していません。チャットページに pi のエラーと
  **再試行**が出ます。直らなければ **設定 → エー
  ジェントのプロセス**で再起動し、それでもだめな
  ら **メンテナンスと修復**で実行環境を再構築し
  てください。
- **パッケージが動かない**：`command not
  found` やライブラリのエラーです。**パッケージ
  の再配置 → 修復**を使ってください。それでもだ
  めなら、そのパッケージに Android 向けのビルド
  はありません。

### データ

- **データの場所**：アプリのプライベート領域の
  `home`、`usr`、`pi-sessions` です。アンインス
  トールで全部消えます。
- **不具合の報告に必要なもの**：**PiKit につい
  て**のバージョンとパッケージ ID、同じページの
  pi のバージョン、そして**エージェントのプロセ
  ス**にある pi の最後のエラーです。

> **ヒント：** **ストレージを確認** はターミナル
> なしで許可が通っていることを確かめます。実行
> 環境が壊れたら **実行環境を再構築** が戻り道
> です。

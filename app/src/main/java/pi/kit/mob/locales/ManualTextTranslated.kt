## 6. エージェントに見えるもの

既定では、エージェントに見えるのは自分のディレク
トリだけで、あなたの写真や書類は存在しない扱いで
す。届かせるには、システムの **すべてのファイル
へのアクセス** 権限と、**設定 → 共有ストレージ
**でオンにしたフォルダーが必要です。

Android のこの権限は全体かゼロかしかないため、実
際にタスクを制限するのはフォルダーのスイッチです：
オフのフォルダーを指すコマンドは実行前に拒否され
ます。オンにしたフォルダーだけが、
`termux-setup-storage` が以前から使う小文字の名
前でエージェントのホームにリンクされます。端末の
`/sdcard/DCIM` は環境内の `~/storage/dcim` です。

この制限が縛るのはエージェントで、ターミナルでは
ありません：`/sdcard` は端末の実際のパスで、アプ
リが「すべてのファイルへのアクセス」を持っていれ
ば、フォルダーの許可に関係なく端末から直接読み書
きできます。

フォルダーはオンにする前に確認を求めます。**共有
ストレージ全体** は残りを覆い、**フォルダーを追
加** は 1 つずつ許可でき（✕ で取り消し）、**すべ
てのアクセスを解除** はリンクを削除し、端末上の
ファイルは削除しません。

2 つのガードはどちらも自分で確認できます：エージ
ェントはワークスペース `~/workspace` の外での再
帰削除を拒否され、PiKit 内の再帰削除もアプリのプ
ライベート領域外を拒否します。**設定 → Pi のアッ
プグレードと修復 → ストレージを確認** が両方を実
際に別プロセスで実行し、項目ごとに報告します。


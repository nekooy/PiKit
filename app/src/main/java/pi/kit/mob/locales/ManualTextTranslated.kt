| `/model` | モデル選択を開く |
| `/clear` | 入力欄を空にする |
| `/stats` | このセッションのターン数・トークン・コスト |
| `/copy` | 最後の回答をコピーする |

`!` で始まるメッセージはモデルに送られずシェルで
実行され、出力は会話に加わります。コマンド一覧の
`!` の行でも同じ入力欄が開きます。

### 添付

- 写真・画像・ファイル。1 つのメッセージに最大
  4 つまでです。
- 4 MB を超える画像は拒否されます。モデルも画
  像入力に対応している必要があり、スイッチはプロ
  ファイルの **モデルパラメータ → 画像入力に対応
  **にあります。
- どの形式のファイルもアプリ内にコピーされ、パ
  スとしてエージェントに渡されます。エージェント
  は自分のツールで開きます。

### 会話の表示

- 終わったターンは、メッセージの下の 1 行（`作
  業 47 秒 · 5 ステップ`）に折りたたまれます。タ
  ップで開きます。最終的な回答は折りたたまれませ
  ん。
- 思考も 1 行です（`思考 · 1200 文字`）。
- ツール呼び出しは 1 行ずつで、✓ か ✕ が付きま
  す。タップで出力を表示します。
- 長押しでコピーできます。回答は Markdown で描
  かれ、コードブロックは横スクロールします。

## 複数の会話を同時に

会話を離れても回答は止まりません。書いている途中
の回答はそのまま届きます。

- バーの **+** は、いまの会話の隣に新しい会話
  を開きます。動いている回答には影響しません。
- 同時に開ける会話は **5** 件までです。6 件目
  を開くと、いちばん長く使われていない会話が閉じ
  られます。5 件とも応答中なら 6 件目は断られ、
  その旨が表示されます。
- **会話履歴**（時計アイコン）では、動いている
  会話に点と**応答中**が付きます。タップするとそ
  の会話に切り替わり、回答は続きます。
- チャットページを左にスワイプすると会話履歴、
  右に戻すとチャットです。

### 会話履歴

- **検索**は保存された全会話のタイトルと本文を
  読みます。
- 行を長押しすると**上部に固定**、**名前を変
  更**、**削除**が出ます。
- バーの**複数選択**でまとめて削除できます。

## エージェントにワークスペースを渡す

ワークスペースはその会話が動くフォルダーで、エー
ジェントが書き込める範囲でもあります。

- 入力欄の最初のボタンで選びます。**ワークスペ
  ースを追加**でどのフォルダーでも追加でき、ファ
  イルへのアクセスがあれば端末のストレージも選べ
  ます。
- **設定 → エージェントのプロセス → デフォルト
  のワークスペース**が、新しい会話の開始位置です。
- 応答中にワークスペースを変えると確認が出ます。
  エージェントを新しいフォルダーで起動し直すため
  です。

### 権限の段階

| 段階 | できること |
| --- | --- |
| 閲覧のみ | 見るだけで、変更もファイルを変えるコマンドの実行もしない |
| ワークスペース内で読み書き | どこでも読め、書き込みはワークスペースの中だけ |
| 完全アクセス | 何も拒否しない |

- 段階はツール呼び出しのたびに検査されるので、
  変更はすぐ効きます。
- 拒否された呼び出しは段階名を添えたツールエラ
  ーとしてエージェントに戻ります。だから再試行せ
  ず、変えたい場所を告げてきます。

### 端末のストレージ

- Android がこのアプリに**すべてのファイルへの
  アクセス**を与えるまで、エージェントに見えるの
  は自分のディレクトリだけです。フォルダー選択に
  は**ファイルへのアクセスを許可**の行があります。
- 許可すると、よく使うフォルダーがエージェント
  のホームにリンクされます。端末のカメラロールは
  `~/storage/dcim` です。リンクは便利のためのも
  ので、権限ではありません。リンク経由の書き込み
  もほかのパスと同じように判断されます。
- この制限が縛るのはエージェントで、ターミナル
  ではありません。`/sdcard` は端末の実際のパスで、
  ターミナルからは直接読み書きできます。
- **設定 → メンテナンスと修復 → ストレージを確
  認**が 2 つのガードを実際に走らせ、項目ごとに
  報告します。

## ファイル

ファイルタブはエージェントのホームを読み取り専用
で閲覧します。エージェントが何を変えたかを、別の
アプリなしで確認できます。

- タイトルの下がパスで、区切りをタップすると上
  に戻れます。
- その下の絞り込み欄はいまのフォルダーだけを絞
  り込み、右のボタンが名前・更新日時・サイズの並
  べ替えです。
- 各行の右端はファイルのサイズ、フォルダーなら
  中の項目数です。
- ファイルをタップするとプレビューします。画像
  はそのまま、テキストは 64 KB まで、それ以外は
  バイナリとして表示します。
- 行を長押しすると**パスをコピー**。ファイルな
  ら**他のアプリで開く**も出ます。
- `/export` の書き出し先は `~/export` で、この
  タブから開けます。

## ターミナル

ターミナルタブは同梱環境の本物のシェルです。複数
のセッションを同時に動かせ、タブを切り替えても動
き続けます。

- キー行にはスマートフォンでは出せないキーが並
  びます：`ESC`、`TAB`、`C-C`、`C-D`、`HOME`、
  `END`、`PGUP`、`PGDN` と記号。`CTRL` と `ALT`
  はトグルです。
- **スクロール**は画面を止めて流れた内容を読む
  ためのもの。改行キーは入力中の行に改行を入れる
  だけで、実行しません。
- ピンチで文字サイズを変えられます。

| コマンド | 用途 |
| --- | --- |
| `pkg install <名前>` | パッケージを入れる |
| `pkg search <語>` | 検索する |
| `pkg upgrade` | すべて更新する |
| `termux-change-repo` | ミラーを変える |
| `termux-setup-storage` | `~/storage` を作る |
| `pi` | pi 自身の画面 |

- `pkg` や `apt` で入れたパッケージはインスト
  ール時に再配置されるので、何もする必要はありま
  せん。
- 別の経路で入れて起動しないパッケージは、**設
  定 → メンテナンスと修復 → インストール済みパッ
  ケージ → パッケージの再配置 → 修復**。
- **実行環境を再構築**はランタイムを展開し直し
  ます。`pkg` で入れたパッケージは記録され、あと
  で戻ります。
- ここで自分で起動した `pi` も同じモデルを使い
  ます。PiKit がプロファイルを pi 自身の設定に書
  き込むためです。

## ウェブ検索

エージェントは最初からウェブ検索できます。**設定
→ 検索設定**は何も変えなくてかまいません。キーが
なければ Exa の無料エンドポイントを使い、混雑時
はレート制限がかかることがあります。

- 画面のスイッチは 6 つだけです：**ウェブアク
  セス**、**検索ワークフロー**、**検索プロバイダ
  ー**、**インライン内容の上限**、**取得タイムア
  ウト**、**プロキシ**。
- その下の**設定項目**が `web-search.json` に
  あるキーの一覧です。**設定項目またはキーを追加
  **で 1 つ増やせ、右端の ✕ で消せます。
- 各サービスの API キーや自前 SearXNG のアドレ
  スもそこで追加します。
- **既定に戻す**はファイルをインストール直後の
  内容に戻します。
- ファイルがこのアプリで読めない JSON になると、
  スイッチの代わりにテキストエディターが出ます。
  そこから直せます。

## 設定の一覧

| 項目 | 内容 |
| --- | --- |
| モデルとプロバイダー | プロバイダー、エンドポイント、キー、モデル |
| 検索設定 | ウェブアクセスのスイッチと設定ファイル |
| パーソナライズ | 起動時の動作、文字サイズ、テーマ、アイコン、アバター |
| 言語 | 英語・簡体中文・日本語 |
| ユーザーマニュアル | このページ |
| エージェントのプロセス | 再起動、ワークスペース、指示、バックグラウンド保護 |
| バックアップと復元 | 書き出して、戻す |
| メンテナンスと修復 | モデル一覧、パッケージ、再構築、ストレージ検査 |
| PiKit について | バージョン、パッケージ ID、パス、更新確認 |

- **テーマ**はシステムに合わせる・ライト・ダー
  クの 3 つだけで、ほかに配色はありません。
- **文字サイズ**は 7 段階で、指を離すと反映さ
  れます。
- **言語**は英語・簡体中文・日本語をすぐ切り替
  えます。

## エージェントのプロセス

- **既定の指示**は PiKit のもので、読み取り専
  用です。プレフィックス、3 つの権限の段階、ワー
  クスペースのルールが書かれており、ビルドごとに
  書き直されます。
- **ユーザーの指示**はあなただけのものです。最
  初は空で、PiKit は決して書き換えません。保存す
  るとエージェントが再起動します。pi は起動時に
  しかこのファイルを読まないためです。
- プロジェクトが自分のフォルダーに置いた
  `AGENTS.md` も読まれ、プロジェクトに近いほうが
  優先されます。
- **エージェントを再起動**は停止と起動を 1 タ
  ップで行います。起動に失敗すると、pi 自身のエ
  ラーがこの行の下に出ます。
- **バックグラウンド保護**は Android のバッテ
  リー最適化の除外です。行の説明が**バッテリー最
  適化はオフです**か**まだバッテリー最適化の対象
  です**かを示し、**除外を申請する**は除外がない
  ときだけ出ます。
- 通知領域の項目は、回答を書いている最中でアプ
  リがバックグラウンドにあるときだけ出ます。何件
  の会話が応答中かを示し、ターンとターンの間には
  消えています。

## バックアップと復元

PiKit をアンインストールすると、プロファイルとそ
のキー、全会話、ワークスペースが消えます。クラウ
ドへの控えは取りません。**設定 → バックアップと
復元**が唯一の備えです。

- アーカイブには設定・プロファイル・会話・ワー
  クスペースが入ります。必要な種類にチェックを入
  れ、**バックアップを作成**を押すと、保存先はシ
  ステムのファイル選択が決めます。
- 最初の 3 種類にはチェックが入っています。
  **ワークスペースのファイル**が外れているのは、
  ワークスペースがプロジェクト一式になりうるから
  です。
- **API キーを含める**は既定でオンです。オフに
  するとアーカイブにキーは 1 つも入りません。
- **バックアップを選ぶ…**は、どの種類か、いつ
  のものか、どのバージョンか、キーが入っているか
  を先に見せてから動きます。
- 復元はエージェントを止め、同名のファイルを上
  書きするだけで、何も削除しません。会話はそれぞ
  れ元の日時のままで、終わるとエージェントが復元
  後の設定で起動します。
- 実行環境そのものはアーカイブに入りません。
  `usr` は APK から展開し直します。

## うまくいかないとき

- **Stream ended without finish_reason**：エン
  ドポイントかネットワークが、最後のチャンクの前
  にストリームを閉じました。エージェントは自分で
  最大 8 回やり直し、たいていはそのまま続きます。
  何度も出るなら回線を変えてみるか、その中継が
  `finish_reason` を送るか提供元に確認してくださ
  い。
- **ツール呼び出しが拒否された**：権限の段階が
  断りました。✕ の付いた行に段階名とパスが出るの
  で、入力欄の下のボタンで段階を変えるか、ワーク
  スペースを変えてください。
- **`pi exited with code 1`**：エージェントの
  プロセスが起動していません。チャットページに
  pi のエラー 1 行目と**再試行**が出ます。直らな
  ければ**設定 → エージェントのプロセス**で再起
  動し、それでもだめなら**メンテナンスと修復**で
  実行環境を再構築してください。
- **モデルが「not found」「unauthorised」を返
  す**：そのキーではそのモデルを使えません。一覧
  を取り直すか、このキーに対して返る ID を入れて
  ください。中継ならベース URL のバージョンセグ

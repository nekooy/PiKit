## 7. 终端

终端页是内置环境里的真实 shell；顶栏的 `>_` 标记
打开它，点左上角的箭头就回来。

### 按键区

- **滚动** 会停住跟随，方便回看滚过去的内容；
  跟随时这个键是强调色，暂停时是红色。
- **四个方向键和 `ESC`** 是手机键盘最不好用的
  几个键，所以各自留在原位。
- **发送文字** 打开一个输入框，里面的内容整段
  送进终端，适合长命令或多行命令。
- **两块键盘**：笔记本按钮打开应用自己的按键面
  板，代替输入法；键盘按钮弹出或收起手机键盘。
- **没有清屏按钮**：它已经去掉了；按键区两端现
  在是新建终端和会话列表。

### 会话

- **可以同时开多个**：`+` 开一个，回到对话页时
  它们照常运行。
- **会话列表**：叠层标记列出所有 shell；点一个
  切过去，垃圾桶关掉一个，**关闭全部终端**在最后
  一行。
- **shell 退出时** 终端上方会有一行写着 `已退
  出（N）`，并给出新建终端的入口。

### 命令

| 命令 | 用途 |
| --- | --- |
| `pkg install <包名>` | 安装软件包 |
| `pkg search <关键字>` | 搜索 |
| `pkg upgrade` | 升级全部 |
| `termux-change-repo` | 换软件源 |
| `termux-setup-storage` | 建 `~/storage` 链接 |
| `ls ~/storage` | 手机存储 |
| `pi` | pi 自己的界面 |

- **软件包会自己重定位**：用 `pkg` 或 `apt` 装
  的包在安装时就会改好，什么都不用做。
- **还是起不来的时候**：**设置 → 维护与修复 →
  软件包重定位 → 修复**。
- **在这里自己敲的 `pi`** 用同一个模型，因为
  PiKit 会把你的配置写进 pi 自己的设置里。

> **提示：** **重建运行环境** 会重新解包运行

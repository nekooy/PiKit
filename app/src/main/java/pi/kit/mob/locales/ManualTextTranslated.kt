## 5. 给 Agent 一个工作区

工作区就是这个对话所在的文件夹，也是 Agent 可以
写入的范围。

### 选一个工作区

- **输入框第一个按钮** 为这个对话选工作区；
  **添加工作区**可以加任何文件夹，给了文件访问权
  限之后手机存储里的也算。
- **默认工作区**：**设置 → Agent 进程 → 默认工
  作区**决定新对话从哪开始，改它不会移动当前这个
  对话。
- **回答期间换工作区** 会先问一句，因为会话目
  录一变，pi 会中断正在跑的这一轮。

### 权限等级

| 等级 | 允许做什么 |
| --- | --- |
| 仅可查看 | 只看不改，也不执行会改动文件的命令 |
| 工作区内读写 | 能读任何地方，只写这个对话的工作区 |
| 完全访问 | 什么都不拒绝 |

- **每次工具调用都检查**，所以改了立刻生效，不
  用重启。
- **被拒绝也是一句话**：工具错误里写明是哪一档，
  Agent 会说出想改什么，而不是反复重试。

### 手机存储

- **所有文件访问权限**：选文件夹页面里的**授予
  文件访问权限**那一行会打开系统页面；拿到之前
  Agent 只看得到自己的目录。
- **链接不是授权**：常用文件夹会链接进 Agent
  的主目录。手机相册是 `~/storage/dcim`，通过链
  接写入的路径照样按等级判断。
- **这个限制管的是 Agent，不是终端**：
  `/sdcard` 是手机存储的真实路径，只要应用拿到了
  所有文件访问权限，终端就能直接读写，跟权限等级
  无关。
- **检查存储**：**设置 → 维护与修复 → 检查存储
  **会逐项打印 ok 或 FAIL，最后给一个汇总。

> **警告：** 任何文件夹都能当工作区，包括
> Agent 自己的主目录；写入范围就是权限等级
> 作用在你选的那个文件夹上。

